select
  d.id,
  'en',
  p.title,
  array[]::text[],
  null,
  null
from payload p
join public.calendar_days d
  on d.country_code = 'CY'
 and d.calendar_code = 'cy-church-of-cyprus'
 and d.language_code = 'el'
 and d.calendar_date = p.calendar_date
on conflict (calendar_day_id, language_code) do update set
  title = excluded.title,
  saints = excluded.saints,
  details = excluded.details,
  fasting_note = excluded.fasting_note;

do $$
declare
  en_count integer;
begin
  select count(*)
    into en_count
  from public.calendar_day_translations t
  join public.calendar_days d on d.id = t.calendar_day_id
  where d.country_code = 'CY'
    and d.calendar_code = 'cy-church-of-cyprus'
    and d.calendar_date between date '2026-01-01' and date '2026-12-31'
    and t.language_code = 'en';

  if en_count <> 365 then
    raise exception 'Expected 365 CY English translations; found %', en_count;
  end if;
end
$$;

