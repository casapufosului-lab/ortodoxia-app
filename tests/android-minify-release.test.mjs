/**
 * Teste pentru partea de C21 din `plugins/with-android-hardening.js`: proprietățile de release care
 * pornesc ofuscarea și tăierea resurselor.
 *
 * Ce apără: `android/gradle.properties` este Git-ignored (trăiește doar în folderul `android/`, care
 * se regenerează la fiecare `expo prebuild`), deci singurul loc durabil în care se pot declara
 * `android.enableMinifyInReleaseBuilds` / `android.enableShrinkResourcesInReleaseBuilds` este pluginul.
 * Șablonul Expo SDK 57 le citește cu `findProperty(...) ?: false` (`app/build.gradle:69,153-155`), deci
 * absența lor înseamnă release neofuscat, fără ca vreun test să observe.
 *
 * Testele rulează funcția reală a pluginului pe liste de proprietăți, nu doar citesc textul sursă.
 */
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const plugin = require(join(ROOT, 'plugins', 'with-android-hardening.js'));

/** `android/gradle.properties` așa cum iese din `expo prebuild` (fără proprietățile de release). */
const BASE_PROPERTIES = [
  { type: 'comment', value: 'Generated by expo prebuild' },
  { type: 'empty' },
  { type: 'property', key: 'newArchEnabled', value: 'true' },
  { type: 'property', key: 'hermesEnabled', value: 'true' },
];

const valueOf = (properties, key) => properties.find((item) => item.type === 'property' && item.key === key)?.value;
const countOf = (properties, key) => properties.filter((item) => item.type === 'property' && item.key === key).length;

test('C21: pluginul pornește ofuscarea și tăierea resurselor în release', () => {
  const result = plugin.applyReleaseBuildProperties(BASE_PROPERTIES);
  assert.equal(valueOf(result, 'android.enableMinifyInReleaseBuilds'), 'true');
  assert.equal(valueOf(result, 'android.enableShrinkResourcesInReleaseBuilds'), 'true');
  // Proprietățile existente rămân neatinse.
  assert.equal(valueOf(result, 'hermesEnabled'), 'true');
  assert.equal(result.length, BASE_PROPERTIES.length + 2);
});

test('C21: rularea repetată nu dublează cheile și rescrie o valoare greșită', () => {
  const once = plugin.applyReleaseBuildProperties(BASE_PROPERTIES);
  const twice = plugin.applyReleaseBuildProperties(once);
  assert.equal(twice.length, once.length, 'a doua rulare nu are voie să adauge intrări');
  assert.equal(countOf(twice, 'android.enableMinifyInReleaseBuilds'), 1);
  assert.equal(countOf(twice, 'android.enableShrinkResourcesInReleaseBuilds'), 1);

  // Dacă cineva a lăsat proprietatea pe `false` în fișier, pluginul o ridică la `true`.
  const stale = [{ type: 'property', key: 'android.enableMinifyInReleaseBuilds', value: 'false' }];
  const repaired = plugin.applyReleaseBuildProperties(stale);
  assert.equal(valueOf(repaired, 'android.enableMinifyInReleaseBuilds'), 'true');
  assert.equal(repaired.length, 2, 'valoarea se rescrie în loc să se adauge o a doua cheie');
});

test('C21: pluginul înregistrează modul gradleProperties, nu doar funcția izolată', () => {
  const config = plugin({});
  const mods = Object.keys(config.mods.android ?? {});
  for (const name of ['manifest', 'appBuildGradle', 'gradleProperties']) {
    assert.ok(mods.includes(name), `pluginul trebuie să înregistreze modul android.${name}`);
  }
});

test('C21: coborârea pragului la false face verificarea să pice (mutant)', () => {
  const expected = (properties) => valueOf(properties, 'android.enableMinifyInReleaseBuilds') === 'true';
  assert.equal(expected(plugin.applyReleaseBuildProperties(BASE_PROPERTIES)), true, 'starea reală trebuie să treacă');

  // Mutant: `applyReleaseBuildProperties` citește exact obiectul exportat, deci îl putem întoarce pe
  // `false` și verificăm că aserțiunea de mai sus POATE cădea — nu că testul doar citește text.
  const original = plugin.RELEASE_BUILD_PROPERTIES['android.enableMinifyInReleaseBuilds'];
  try {
    plugin.RELEASE_BUILD_PROPERTIES['android.enableMinifyInReleaseBuilds'] = 'false';
    assert.equal(
      expected(plugin.applyReleaseBuildProperties(BASE_PROPERTIES)),
      false,
      'mutantul trebuie prins de verificarea de mai sus',
    );
  } finally {
    plugin.RELEASE_BUILD_PROPERTIES['android.enableMinifyInReleaseBuilds'] = original;
  }
  assert.equal(original, 'true');
});
